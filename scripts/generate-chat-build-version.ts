import { execFileSync } from 'node:child_process'
import { randomUUID } from 'node:crypto'
import fs from 'node:fs/promises'
import path from 'node:path'

const CHAT_BUILD_VERSION = {
  OUTPUT_PATH: path.join(
    process.cwd(),
    'features/chat/config/chat-build-version.generated.ts',
  ),
  GIT_COMMAND: 'git',
  GIT_ARGUMENTS: ['rev-parse', 'HEAD'],
  UNKNOWN_COMMIT_PREFIX: 'build-',
} as const

function resolveChatBuildVersion(): string {
  try {
    const commitSha = execFileSync(
      CHAT_BUILD_VERSION.GIT_COMMAND,
      CHAT_BUILD_VERSION.GIT_ARGUMENTS,
      {
        cwd: process.cwd(),
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      },
    ).trim()

    if (commitSha) {
      return commitSha
    }
  } catch {
    // Source archives may not contain Git metadata. Each build still needs its own version.
  }

  return `${CHAT_BUILD_VERSION.UNKNOWN_COMMIT_PREFIX}${randomUUID()}`
}

async function main(): Promise<void> {
  const buildVersion = resolveChatBuildVersion()
  const generatedSource = [
    '// Generated by scripts/generate-chat-build-version.ts. Do not edit.',
    `export const GENERATED_CHAT_BUILD_VERSION = ${JSON.stringify(buildVersion)} as const`,
    '',
  ].join('\n')

  await fs.writeFile(CHAT_BUILD_VERSION.OUTPUT_PATH, generatedSource)
  console.log('✅ Generated chat build version.')
}

// eslint-disable-next-line unicorn/prefer-top-level-await
void (async () => {
  try {
    await main()
  } catch (error) {
    console.error('Failed to generate chat build version:', error)
    process.exitCode = 1
  }
})()
